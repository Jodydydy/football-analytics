"""
Трекинг: связывание детекций между кадрами.

Детектор не знает, что человек на кадре 100 и на кадре 101 — один и тот же.
Трекер присваивает каждому объекту track_id, стабильный во времени. Без этого
подсчёт невозможен: один прошедший человек дал бы событие на каждом кадре.
"""
from __future__ import annotations

import supervision as sv


class Tracker:
    """
    Обёртка над ByteTrack.

    Идея ByteTrack: сопоставлять с существующими треками не только уверенные
    детекции, но и слабые. Человек, которого частично загородили, даёт низкий
    conf — обычный трекер его теряет и заводит новый ID при следующем появлении.
    ByteTrack пытается сначала пристроить слабую детекцию к уже существующему
    треку, и разрывов становится меньше.

    Почему это важно именно здесь: разрыв трека посреди прохода = один человек
    посчитан дважды (ID switch). Для счётчика через линию это прямая ошибка
    в метрике.

    lost_track_buffer
        сколько кадров трек живёт после того, как объект пропал из виду.
        Больше — переживаем длинные перекрытия, но растёт риск приклеить
        вернувшийся трек к другому человеку.

    minimum_consecutive_frames
        сколько кадров подряд нужно видеть объект, чтобы завести трек.
        Отсекает одиночные ложные детекции — они не успевают стать треком
        и не доходят до счётчика.
    """

    def __init__(self,
                 lost_track_buffer: int = 30,
                 minimum_consecutive_frames: int = 1):
        self.tracker = sv.ByteTrack(
            lost_track_buffer=lost_track_buffer,
            minimum_consecutive_frames=minimum_consecutive_frames,
        )

    def update(self, detections: sv.Detections) -> sv.Detections:
        """Проставить tracker_id. Возвращает те же детекции с заполненным полем."""
        return self.tracker.update_with_detections(detections)

    def reset(self) -> None:
        """Сбросить состояние — нужно при переходе к новой записи."""
        self.tracker.reset()
